//go:build ignore

// zones_gen writes zones.go, the IANA time zone identifiers, from the time
// zone database of the Go toolchain that runs it:
//
//	go run zones_gen.go
//
// It is run by hand when Go ships a database with a new zone. There is no
// go:generate directive: the builders run go generate, and each would rewrite
// the list from the database of its own toolchain.
package main

import (
	"archive/zip"
	"bytes"
	"fmt"
	"log"
	"os"
	"os/exec"
	"path/filepath"
	"regexp"
	"slices"
	"strings"
)

func main() {
	out, err := exec.Command("go", "env", "GOROOT").Output()
	if err != nil {
		log.Fatal(err)
	}

	root := filepath.Join(strings.TrimSpace(string(out)), "lib", "time")
	z, err := zip.OpenReader(filepath.Join(root, "zoneinfo.zip"))
	if err != nil {
		log.Fatal(err)
	}

	defer z.Close()

	var names []string
	for _, f := range z.File {
		// Factory is a zone of the database for machines whose zone is not
		// set yet, which ICU does not take for an identifier.
		if !strings.HasSuffix(f.Name, "/") && f.Name != "Factory" {
			names = append(names, f.Name)
		}
	}
	slices.Sort(names)

	version := "an unknown version"
	if b, err := os.ReadFile(filepath.Join(root, "update.bash")); err == nil {
		if m := regexp.MustCompile(`(?m)^DATA=(\S+)`).FindSubmatch(b); m != nil {
			version = string(m[1])
		}
	}

	var b bytes.Buffer
	fmt.Fprintf(&b, `// Code generated by zones_gen.go from tzdata %s; DO NOT EDIT.

package intl // import "modernc.org/quickjs/intl"

// zoneNames are the IANA time zone identifiers, zones and links, one per line,
// as the time zone database spells them.
const zoneNames = `+"`", version)
	b.WriteString(strings.Join(names, "\n"))
	b.WriteString("`\n")
	if err := os.WriteFile("zones.go", b.Bytes(), 0o644); err != nil {
		log.Fatal(err)
	}
}
